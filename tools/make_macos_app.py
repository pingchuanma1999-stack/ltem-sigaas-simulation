"""Build a double-clickable macOS app bundle that launches the GUI from this checkout.

    .venv/bin/python tools/make_macos_app.py [--dest ~/Applications]

The bundle is a thin launcher: it runs `<repo>/.venv/bin/python -m ltemsim_gui`, so edits to the
simulation code or the GUI take effect on the next start without rebuilding.  Re-run this script
if the repository or its .venv moves.  Logs go to ~/Library/Logs/LTEMSim.log.
"""
import argparse
import os
import plistlib
import shutil
import stat
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP_NAME = "LTEM Sim"
BUNDLE_ID = "io.github.pingchuanma.ltemsim"

LAUNCHER = """#!/bin/bash
# LTEM Sim launcher (generated by tools/make_macos_app.py)
REPO={repo}
PY="$REPO/.venv/bin/python"
LOG="$HOME/Library/Logs/LTEMSim.log"
if [ ! -x "$PY" ]; then
  /usr/bin/osascript -e 'display alert "LTEM Sim cannot start" message "Python environment not found: '"$PY"'\\n\\nIn the project folder run:\\npython3 -m venv .venv && .venv/bin/pip install -r requirements-gui.txt\\nthen run tools/make_macos_app.py again." as critical'
  exit 1
fi
cd "$REPO" || exit 1
echo "=== $(date) start ===" >> "$LOG"
exec "$PY" -m ltemsim_gui "$@" >> "$LOG" 2>&1
"""


def build(dest: Path) -> Path:
    app = dest / f"{APP_NAME}.app"
    if app.exists():
        shutil.rmtree(app)
    macos = app / "Contents" / "MacOS"
    res = app / "Contents" / "Resources"
    macos.mkdir(parents=True)
    res.mkdir(parents=True)
    icns = ROOT / "ltemsim_gui" / "assets" / "AppIcon.icns"
    if not icns.exists():
        subprocess.run([str(ROOT / ".venv" / "bin" / "python"), str(ROOT / "tools" / "make_icon.py")], check=True)
    shutil.copy(icns, res / "AppIcon.icns")
    exe = macos / "LTEMSim"
    exe.write_text(LAUNCHER.format(repo=shlex_quote(str(ROOT))))
    exe.chmod(exe.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    info = {
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleVersion": "1.0.0",
        "CFBundleShortVersionString": "1.0",
        "CFBundlePackageType": "APPL",
        "CFBundleExecutable": "LTEMSim",
        "CFBundleIconFile": "AppIcon",
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "NSRequiresAquaSystemAppearance": False,
        "LSApplicationCategoryType": "public.app-category.education",
        "NSHumanReadableCopyright": "SI-GaAs near-field LTEM simulation",
    }
    with open(app / "Contents" / "Info.plist", "wb") as fh:
        plistlib.dump(info, fh)
    # refresh Finder / Launch Services so the icon shows immediately
    lsreg = "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister"
    if os.path.exists(lsreg):
        subprocess.run([lsreg, "-f", str(app)], check=False)
    subprocess.run(["touch", str(app)], check=False)
    return app


def shlex_quote(s: str) -> str:
    import shlex
    return shlex.quote(s)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", default=str(Path.home() / "Applications"))
    a = ap.parse_args()
    dest = Path(os.path.expanduser(a.dest))
    dest.mkdir(parents=True, exist_ok=True)
    print("built", build(dest))
